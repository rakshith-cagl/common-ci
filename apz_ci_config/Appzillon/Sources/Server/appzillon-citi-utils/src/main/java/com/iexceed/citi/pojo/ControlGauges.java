package com.iexceed.citi.pojo;

public class ControlGauges {
    private String gaugeMin;
    private String gaugeMax;
    private String gaugeColor;

    public String getGaugeMin() {
        return gaugeMin;
    }

    public void setGaugeMin(String gaugeMin) {
        this.gaugeMin = gaugeMin;
    }

    public String getGaugeMax() {
        return gaugeMax;
    }

    public void setGaugeMax(String gaugeMax) {
        this.gaugeMax = gaugeMax;
    }

    public String getGaugeColor() {
        return gaugeColor;
    }

    public void setGaugeColor(String gaugeColor) {
        this.gaugeColor = gaugeColor;
    }

}
