package com.iexceed.citi.dataobj;

public class ScreenResponseJson {
    private String intfJson;
    private String screenDefJson;
    private String screenDesignJson;
    private String productId;
    private String tempalate;
    private String layoutDef;

    public String getIntfJson() {
        return intfJson;
    }

    public void setIntfJson(String intfJson) {
        this.intfJson = intfJson;
    }

    public String getScreenDefJson() {
        return screenDefJson;
    }

    public void setScreenDefJson(String screenDefJson) {
        this.screenDefJson = screenDefJson;
    }

    public String getScreenDesignJson() {
        return screenDesignJson;
    }

    public void setScreenDesignJson(String screenDesignJson) {
        this.screenDesignJson = screenDesignJson;
    }

    public String getProductId() {
        return productId;
    }

    public void setProductId(String productId) {
        this.productId = productId;
    }

    public String getTempalate() {
        return tempalate;
    }

    public void setTempalate(String tempalate) {
        this.tempalate = tempalate;
    }

    public String getLayoutDef() {
        return layoutDef;
    }

    public void setLayoutDef(String layoutDef) {
        this.layoutDef = layoutDef;
    }


}
